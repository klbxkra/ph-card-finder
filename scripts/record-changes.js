// Records what changed between data versions into history.js (window.PHCC_HISTORY, newest first).
//   node scripts/record-changes.js            compare data.js with the last committed version and add an entry
//   node scripts/record-changes.js --rebuild  rebuild the whole history from git, then add the working copy
// Run it after editing data.js and before committing.
const fs = require("fs");
const path = require("path");
const vm = require("vm");
const { execFileSync } = require("child_process");

const root = path.join(__dirname, "..");
const histFile = path.join(root, "history.js");

function load(src) {
  const ctx = { window: {} };
  vm.runInNewContext(src, ctx);
  return ctx.window.PHCC_DATA;
}
const git = (...args) => execFileSync("git", args, { cwd: root, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
const peso = n => "₱" + Math.round(n).toLocaleString("en-PH");
const income = c => c.minIncome != null ? peso(c.minIncome) : c.estIncome != null ? `~${peso(c.estIncome)} (estimate)` : "not published";
const fee = c => !c.fee ? "—" : c.fee.life ? "₱0 for life" : peso(c.fee.annual);
const earnKey = e => JSON.stringify(e ? { u: e.unit, b: e.base, c: e.cats, cc: e.cashCats, eco: e.eco, pv: e.pv, tm: e.toMiles, cm: e.capMonth, cy: e.capYear, r: e.rotating, f: e.flexPick, ms: e.minSpend } : null);
const promoKey = p => `${p.title}|${p.until || ""}`;

function diff(prev, cur) {
  const before = new Map(prev.cards.map(c => [c.id, c]));
  const after = new Map(cur.cards.map(c => [c.id, c]));
  const changes = [];
  for (const [id, c] of after) {
    if (!before.has(id)) { changes.push({ id, bank: c.bank, name: c.name, kind: "added" }); continue; }
    const o = before.get(id); const fields = [];
    const cmp = (label, a, b) => { if (a !== b) fields.push({ f: label, from: a, to: b }); };
    cmp("Status", o.status, c.status);
    if (c.status !== "closed" && c.status !== "invite") {
      cmp("Annual fee", fee(o), fee(c));
      cmp("Income floor", income(o), income(c));
      cmp("Forex fee", o.fx != null ? o.fx + "%" : "—", c.fx != null ? c.fx + "%" : "—");
      cmp("Interest", o.apr != null ? o.apr + "%/mo" : "—", c.apr != null ? c.apr + "%/mo" : "—");
      if (earnKey(o.earn) !== earnKey(c.earn)) fields.push({ f: "Rewards", from: "", to: "Earn rates, caps or point value changed" });
      cmp("Apply link", (o.apply || {}).url || "—", (c.apply || {}).url || "—");
      const op = new Set((o.promos || []).map(promoKey)), np = new Set((c.promos || []).map(promoKey));
      for (const p of c.promos || []) if (!op.has(promoKey(p))) fields.push({ f: "New promo", from: "", to: p.title + (p.until ? ` (to ${p.until})` : "") });
      for (const p of o.promos || []) if (!np.has(promoKey(p))) fields.push({ f: "Promo removed", from: p.title, to: "" });
    }
    if (fields.length) changes.push({ id, bank: c.bank, name: c.name, kind: "changed", fields });
  }
  for (const [id, o] of before) if (!after.has(id)) changes.push({ id, bank: o.bank, name: o.name, kind: "removed" });
  return changes;
}

function entry(prev, cur) {
  const log = (cur.meta.changelog || [])[0] || {};
  return { version: cur.meta.version, date: cur.meta.dataAsOf, note: log.note || "", changes: diff(prev, cur) };
}

function readHistory() {
  if (!fs.existsSync(histFile)) return [];
  const ctx = { window: {} };
  vm.runInNewContext(fs.readFileSync(histFile, "utf8"), ctx);
  return ctx.window.PHCC_HISTORY || [];
}
function writeHistory(list) {
  fs.writeFileSync(histFile, "// Generated by scripts/record-changes.js. Newest first.\nwindow.PHCC_HISTORY = " + JSON.stringify(list, null, 1) + ";\n");
}

const working = load(fs.readFileSync(path.join(root, "data.js"), "utf8"));
let history;
if (process.argv.includes("--rebuild")) {
  const commits = git("log", "--format=%H", "--reverse", "--", "data.js").trim().split("\n").filter(Boolean);
  const versions = commits.map(h => load(git("show", `${h}:data.js`)));
  history = [];
  for (let i = 1; i < versions.length; i++) if (versions[i].meta.version !== versions[i - 1].meta.version) history.unshift(entry(versions[i - 1], versions[i]));
  const last = versions[versions.length - 1];
  if (last && last.meta.version !== working.meta.version) history.unshift(entry(last, working));
} else {
  history = readHistory();
  const head = load(git("show", "HEAD:data.js"));
  if (head.meta.version === working.meta.version) { console.log("data.js version unchanged; nothing recorded"); process.exit(0); }
  history = history.filter(h => h.version !== working.meta.version);
  history.unshift(entry(head, working));
}
writeHistory(history);
console.log(`history.js: ${history.length} versions; latest ${history[0] ? history[0].version + " with " + history[0].changes.length + " card changes" : "none"}`);
